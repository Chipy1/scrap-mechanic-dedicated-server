#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CREDS="${1:-$HOME/Documents/SMServer_creds.txt}"
ENV_FILE="$ROOT/.env"

[[ -f "$CREDS" ]] || { echo "credentials file not found: $CREDS" >&2; exit 1; }

umask 077

python3 - "$CREDS" "$ENV_FILE" <<'PY'
from __future__ import annotations

import secrets
import sys
from pathlib import Path

creds_path = Path(sys.argv[1])
env_path = Path(sys.argv[2])


def parse_file(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.is_file():
        return values
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if value[:1] in {"'", '"'}:
            quote_char = value[0]
            end = value.find(quote_char, 1)
            if end > 0:
                value = value[1:end]
        else:
            value = value.split("#", 1)[0].strip()
        values[key] = value
    return values


def quote(value: str) -> str:
    if "\n" in value or "\r" in value:
        raise SystemExit("credential contains a newline; refusing to write .env")
    if "'" not in value:
        return f"'{value}'"
    if '"' not in value and "\\" not in value:
        return f'"{value}"'
    raise SystemExit("credential contains unsupported quote characters")


creds = parse_file(creds_path)
existing = parse_file(env_path)
login = creds.get("SERVER_STEAM_USER_LOGIN", "")
password = creds.get("SERVER_STEAM_USER_PASSWORD", "")
if not login or not password:
    raise SystemExit(
        f"{creds_path} must contain SERVER_STEAM_USER_LOGIN and "
        "SERVER_STEAM_USER_PASSWORD"
    )

token = existing.get("SM_API_TOKEN") or secrets.token_urlsafe(32)
save_name = existing.get("SAVE_NAME", "something-test")
game_mode = existing.get("GAME_MODE", "")
if not game_mode:
    game_mode = "custom" if existing.get("IS_CUSTOM_GAME", "false").strip().lower() in {"1", "true", "yes", "on"} else "survival"
steam_id = existing.get("SM_STEAM_ID", "")
backup_auto = existing.get("SM_BACKUP_AUTO", "true")
backup_interval = existing.get("SM_BACKUP_INTERVAL_MINUTES", "15")
retention_days = existing.get("SM_BACKUP_RETENTION_DAYS", "7")
retention_weeks = existing.get("SM_BACKUP_RETENTION_WEEKS", "4")
require_stopped = existing.get("SM_REQUIRE_SERVER_STOPPED", "true")
api_port = existing.get("SM_API_PORT", "8080")
panel_user = existing.get("SM_PANEL_USER", "admin")
panel_password = existing.get("SM_PANEL_PASSWORD") or secrets.token_urlsafe(24)
panel_secret = existing.get("SM_PANEL_SECRET") or secrets.token_hex(32)
panel_bind = existing.get("SM_PANEL_BIND", "127.0.0.1")
panel_port = existing.get("SM_PANEL_PORT", "8081")
puid = existing.get("PUID", "1000")
pgid = existing.get("PGID", "1000")
tz = existing.get("TZ", "UTC")

lines = [
    "# Generated by scripts/import-creds.sh; keep mode 600.",
    f"SERVER_STEAM_USER_LOGIN={quote(login)}",
    f"SERVER_STEAM_USER_PASSWORD={quote(password)}",
    f"SAVE_NAME={quote(save_name)}",
    f"GAME_MODE={quote(game_mode)}  # custom|survival|creative",
    f"SM_API_TOKEN={quote(token)}",
    f"SM_API_PORT={quote(api_port)}",
    f"SM_PANEL_USER={quote(panel_user)}",
    f"SM_PANEL_PASSWORD={quote(panel_password)}",
    f"SM_PANEL_SECRET={quote(panel_secret)}",
    f"SM_PANEL_BIND={quote(panel_bind)}",
    f"SM_PANEL_PORT={quote(panel_port)}",
    f"SM_STEAM_ID={quote(steam_id)}",
    f"SM_BACKUP_AUTO={quote(backup_auto)}",
    f"SM_BACKUP_INTERVAL_MINUTES={quote(backup_interval)}",
    f"SM_BACKUP_RETENTION_DAYS={quote(retention_days)}",
    f"SM_BACKUP_RETENTION_WEEKS={quote(retention_weeks)}",
    f"SM_REQUIRE_SERVER_STOPPED={quote(require_stopped)}",
    "SM_SKIP_UPDATE=false",
    "SM_STEAM_LOGIN_TIMEOUT=600",
    "SM_GAME_START_TIMEOUT=300",
    "SM_STEAMCMD_TIMEOUT=1800",
    "SM_LOW_GRAPHICS=true",
    "SM_FPS_CAP=10",
    "SM_GAME_EXTRA_ARGS=",
    "SM_NULL_RENDER=true",
    "WINEDLLOVERRIDES=d3d11=n,b",
    "LP_NUM_THREADS=2",
    "PROTON_USE_XALIA=0",
    "SteamNoOverlay=1",
    "SDL_AUDIODRIVER=dummy",
    f"PUID={quote(puid)}",
    f"PGID={quote(pgid)}",
    f"TZ={quote(tz)}",
    "",
]
env_path.write_text("\n".join(lines), encoding="utf-8")
env_path.chmod(0o600)
print(f"wrote {env_path} (mode 600)")
PY
